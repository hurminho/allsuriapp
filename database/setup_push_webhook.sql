-- Supabase Database Webhook 설정
--
-- notifications 테이블 INSERT 시 send-push-webhook 1회만 호출 (FCM 단일 경로).
-- 앱/서버에서 send-push를 직접 호출하면 Webhook과 중복되어 푸시 2회 수신됨.
--
-- 설정 방법:
-- Supabase 대시보드 → Database → Webhooks → Create a new hook
--
-- Hook 설정:
--   Name: push_notification_on_insert
--   Table: notifications (public schema)
--   Events: INSERT
--   Type: HTTP Request
--   URL: https://api.allsuri.app/api/notifications/send-push-webhook
--   HTTP Method: POST
--   Timeout: 15000 (5초면 FCM 지연 시 Supabase가 재시도 → 푸시 2회)
--   Headers (둘 다 필수):
--     Content-Type: application/json
--     Authorization: Bearer <ADMIN_TOKEN>   ← Content-Type만 있으면 401로 FCM 미발송
--
-- Payload (자동으로 Supabase가 보내는 형식):
-- {
--   "type": "INSERT",
--   "table": "notifications",
--   "record": {
--     "id": "...",
--     "userid": "...",
--     "title": "...",
--     "body": "...",
--     ...
--   }
-- }

